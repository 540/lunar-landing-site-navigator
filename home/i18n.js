/** ZONES of index.html in `lang`, changed in place: in Spanish they stay as they are. */
export function localizeZones(zones, lang) {
  if (lang !== 'en') return zones;
  for (const z of zones) Object.assign(z, ZONES_EN[z.id]);
  return zones;
}

/** EXPLORE of index.html in `lang`, changed in place; a link without an English label keeps the Spanish one. */
export function localizeExplore(zones, lang) {
  if (lang !== 'en') return zones;
  for (const z of zones) {
    const own = EXPLORE_EN[z.id];
    if (!own) continue;
    const { links, ...rest } = own;
    Object.assign(z, rest);
    if (links) z.links = z.links.map(([href, label], i) => [href, links[i] ?? label]);
  }
  return zones;
}
