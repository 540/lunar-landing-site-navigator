// The reason of a verdict comes in Spanish from the fixed templates of planner/src/rules.js and ranking.js. Each pattern
// takes its first letter in either case (ranking.js lowercases it after «La que más aprieta:»); what no pattern knows
// stays in Spanish.
const REASONS = [
  [/^Por poco: /, 'Only just: '],
  [/^Cumple todas las reglas\. La que más aprieta: /, 'Meets every rule. The tightest one: '],
  [/[Ss]in datos de visibilidad para toda la misión/g, 'No visibility data for the whole mission'],
  [/[Ee]l periodo consultado no cubre toda la misión/g, 'The period queried does not cover the whole mission'],
  [/[Ee]l Sol no se ve al aterrizar ni vuelve a salir en el periodo consultado/g, 'The Sun is not visible at landing and does not rise again in the period queried'],
  [/[Ee]l Sol no se ve al aterrizar; sale en /g, 'The Sun is not visible at landing; sunrise in '],
  [/[Ee]l Sol se ve al aterrizar/g, 'The Sun is visible at landing'],
  [/[Ll]a Tierra no se ve al aterrizar ni vuelve a salir en el periodo consultado/g, 'The Earth is not visible at landing and does not rise again in the period queried'],
  [/[Ll]a Tierra no se ve al aterrizar; sale en /g, 'The Earth is not visible at landing; Earthrise in '],
  [/[Ll]a Tierra se ve al aterrizar/g, 'The Earth is visible at landing'],
  [/[Aa]l menos /g, 'At least '],
  [/ de sol tras aterrizar/g, ' of sunlight after landing'],
  [/[Ss]ombra más larga: /g, 'Longest shadow: '],
  [/ de la misión con sol y Tierra/g, ' of the mission with Sun and Earth'],
  [/ de la misión con sol/g, ' of the mission in sunlight'],
  [/[Hh]ueco más largo sin Tierra: /g, 'Longest gap without Earth: '],
  [/[Tt]ierra visible el (.+?) de la misión/g, 'Earth visible for $1 of the mission'],
  [/[Ss]in datos de pendiente: no se pidió a la API/g, 'No slope data: it was not requested from the API'],
  [/[Ss]in datos de pendiente: el punto queda fuera del DEM o el servidor no lo tiene/g, 'No slope data: the point is outside the DEM or the server does not have it'],
  [/[Pp]endiente de (\S+) en (\S+) m/g, 'Slope of $1 over $2 m'],
  [/; con el DEM de (\S+) m\/px no se puede certificar en (\S+) m/g, '; with the $1 m/px DEM it cannot be certified over $2 m'],
  [/\(mínimo /g, '(minimum '],
  [/\(máximo /g, '(maximum '],
  [/\(la batería aguanta /g, '(the battery lasts '],
  [/(\d),(\d)/g, '$1.$2'],
  [/(\d) %/g, '$1%'],
];
const lowerFirst = s => s.charAt(0).toLowerCase() + s.slice(1);
export function reasonToEnglish(reason) {
  let out = String(reason ?? '');
  for (const [re, en] of REASONS) {
    out = out.replace(re, (match, ...groups) => {
      const text = en.replace(/\$(\d)/g, (_, n) => groups[n - 1]);
      return /^[a-zà-ÿ]/.test(match) && /^[A-Z]/.test(text) && !/^(Earth|Sun)\b/.test(text) ? lowerFirst(text) : text;
    });
  }
  return out;
}

