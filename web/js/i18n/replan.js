// The domain (planner/src/rules.js) writes its reasons in Spanish from a few fixed templates, without a code in the
// day sweep: English rewrites each template. An unknown text stays as it is.
const REASONS_EN = [
  [/^El periodo consultado no cubre toda la misión$/, 'The queried period does not cover the whole mission'],
  [/^El Sol se ve al aterrizar$/, 'The Sun is visible at landing'],
  [/^El Sol no se ve al aterrizar ni vuelve a salir en el periodo consultado$/, 'The Sun is not visible at landing and does not rise again in the queried period'],
  [/^El Sol no se ve al aterrizar; sale en (.+)$/, 'The Sun is not visible at landing; it rises in $1'],
  [/^La Tierra se ve al aterrizar$/, 'The Earth is visible at landing'],
  [/^La Tierra no se ve al aterrizar ni vuelve a salir en el periodo consultado$/, 'The Earth is not visible at landing and does not rise again in the queried period'],
  [/^La Tierra no se ve al aterrizar; sale en (.+)$/, 'The Earth is not visible at landing; it rises in $1'],
  [/^Al menos (.+) de sol tras aterrizar$/, 'At least $1 of sunlight after landing'],
  [/^(.+) de sol tras aterrizar$/, '$1 of sunlight after landing'],
  [/^Sombra más larga: (.+)$/, 'Longest shadow: $1'],
  [/^(.+) de la misión con sol y Tierra$/, '$1 of the mission with Sun and Earth'],
  [/^(.+) de la misión con sol$/, '$1 of the mission in sunlight'],
  [/^Hueco más largo sin Tierra: (.+)$/, 'Longest gap without the Earth: $1'],
  [/^Tierra visible el (.+) de la misión$/, 'Earth visible $1 of the mission'],
  [/^Sin datos de pendiente: no se pidió a la API$/, 'No slope data: it was not requested from the API'],
  [/^Sin datos de pendiente: el punto queda fuera del DEM o el servidor no lo tiene$/, 'No slope data: the point is outside the DEM or the server does not have it'],
  [/^Pendiente de (.+?) en (\S+) m(.*)$/, 'Slope of $1 over $2 m$3'],
];
const LIMITS_EN = [[/\(mínimo /g, '(minimum '], [/\(máximo /g, '(maximum '], [/\(la batería aguanta /g, '(battery lasts '],
  [/; con el DEM de (\S+) m\/px no se puede certificar en (\S+) m/, '; with the $1 m/px DEM it cannot be certified over $2 m']];
function reasonEn(text) {
  if (!text) return text;
  const [, s, limit] = String(text).match(/^(.*?)((?: \((?:mínimo|máximo|la batería aguanta) [^)]*\))?(?:; con el DEM .*)?)$/);
  let out = s;
  for (const [re, en] of REASONS_EN) if (re.test(s)) { out = s.replace(re, en); break; }
  out += LIMITS_EN.reduce((x, [re, en]) => x.replace(re, en), limit);
  return out.replace(/(\d),(\d)/g, '$1.$2');
}

